"""Export a code's base matrix as memory-initialisation files for the RTL.

The decoder needs the base matrix in hardware: for every layer, the list of
(base column, circulant shift) pairs. This writes it in the two forms Vivado
accepts directly — ``$readmemh`` text and a Block Memory Generator ``.coe`` —
plus a SystemVerilog header with the derived parameters.

    uv run python scripts/export_code_mem.py --code codes/mother_low.npz --out rtl/gen

Edge record layout (one word per non-zero base entry, in layer order, then by
increasing base column, which is the neighbour order of spec section 3.1):

    [ col_bits-1 : 0 ]            base column index
    [ col_bits+shift_bits-1 : col_bits ]  circulant shift

``layer_ptr`` gives the first edge index of each layer.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from model import code as qc  # noqa: E402


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--code", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--name", default=None, help="prefix for the generated files")
    args = ap.parse_args()

    code = qc.load_code(args.code)
    name = args.name or args.code.stem
    args.out.mkdir(parents=True, exist_ok=True)

    col_bits = int(np.ceil(np.log2(code.n_b)))
    shift_bits = int(np.ceil(np.log2(code.z)))
    word_bits = col_bits + shift_bits
    hex_digits = (word_bits + 3) // 4

    words = [(int(s) << col_bits) | int(c)
             for c, s in zip(code.edge_col, code.edge_shift)]

    (args.out / f"{name}_edges.mem").write_text(
        "\n".join(f"{w:0{hex_digits}x}" for w in words) + "\n", encoding="utf-8")
    (args.out / f"{name}_layer_ptr.mem").write_text(
        "\n".join(f"{int(v):04x}" for v in code.layer_ptr) + "\n", encoding="utf-8")

    coe = ["memory_initialization_radix=16;", "memory_initialization_vector="]
    coe.append(",\n".join(f"{w:0{hex_digits}x}" for w in words) + ";")
    (args.out / f"{name}_edges.coe").write_text("\n".join(coe) + "\n", encoding="utf-8")

    header = f"""// Generated by scripts/export_code_mem.py from {args.code.name}
// Do not edit by hand; regenerate when the code changes.
`ifndef {name.upper()}_PARAMS_SVH
`define {name.upper()}_PARAMS_SVH

  localparam int unsigned N_B        = {code.n_b};   // base columns
  localparam int unsigned M_B        = {code.m_b};   // base rows (layers)
  localparam int unsigned Z          = {code.z};     // lifting size
  localparam int unsigned N_BITS     = {code.n};     // codeword length
  localparam int unsigned M_BITS     = {code.m};     // syndrome length
  localparam int unsigned N_EDGES    = {code.n_edges_base};
  localparam int unsigned COL_BITS   = {col_bits};
  localparam int unsigned SHIFT_BITS = {shift_bits};
  localparam int unsigned EDGE_BITS  = {word_bits};
  localparam int unsigned MAX_ROW_DEG = {int(np.diff(code.layer_ptr).max())};

`endif
"""
    (args.out / f"{name}_params.svh").write_text(header, encoding="utf-8")

    print(f"code {args.code.name}: n={code.n} m={code.m} Z={code.z} "
          f"base {code.m_b}x{code.n_b}, {code.n_edges_base} edges")
    print(f"  edge word: {word_bits} bits ({col_bits} column + {shift_bits} shift)")
    print(f"  max row degree: {int(np.diff(code.layer_ptr).max())}")
    print(f"wrote {name}_edges.mem, {name}_layer_ptr.mem, {name}_edges.coe, "
          f"{name}_params.svh to {args.out}")


if __name__ == "__main__":
    main()
